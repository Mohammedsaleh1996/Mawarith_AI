def _norm(s: str) -> str:
    s = re.sub(r"[\u064b-\u0652\u0670]", "", str(s or ""))
    s = s.replace("أ","ا").replace("إ","ا").replace("آ","ا").replace("ى","ي")
    s = s.replace("ؤ","و").replace("ئ","ي").replace("ة","ه")
    return re.sub(r"\s+", " ", s).strip().lower()


def dialect_name(dialect_obj_or_name) -> str:
    if isinstance(dialect_obj_or_name, str):
        return dialect_obj_or_name
    return getattr(dialect_obj_or_name, "name", "standard")


def _opening(title: str, dialect: str, level: str) -> str:
    if level == "simple":
        if dialect == "egyptian":
            return f"ببساطة: {title} يعني كده:"
        if dialect in ("gulf", "saudi"):
            return f"ببساطة: المقصود بـ {title} كذا:"
        if dialect == "shami":
            return f"ببساطة: {title} يعني هيك:"
        if dialect == "moroccan":
            return f"ببساطة: {title} معناها هكذا:"
        if dialect == "sudanese":
            return f"ببساطة: {title} معناها كده:"
        return f"ببساطة: {title} هو:"
    if dialect == "egyptian":
        return f"أيوه، {title} في المواريث معناه:"
    if dialect in ("gulf", "saudi"):
        return f"المقصود بـ {title} في الميراث هو:"
    if dialect == "shami":
        return f"{title} بالمواريث معناه:"
    return f"{title}:"


def render_concept(key: str, dialect="standard", level: str="normal") -> str:
    c = CONCEPTS[key]
    d = dialect_name(dialect)
    lines: List[str] = []
    lines.append(_opening(c.title, d, level))
    lines.append("")
    lines.append(c.definition)

    if level == "simple":
        if c.example:
            lines += ["", "مثال سريع:", c.example]
        if c.caution:
            lines += ["", "تنبيه:", c.caution]
        return "\n".join(lines).strip()

    if c.points:
        lines += ["", "النقاط المهمة:"]
        lines += [f"- {p}" for p in c.points]

    if c.cases and level in ("normal", "detailed"):
        lines += ["", "الحالات:"]
        lines += [f"- {p}" for p in c.cases]

    if c.example and level in ("normal", "example", "detailed"):
        lines += ["", "مثال:", c.example]

    if level == "example" and not c.example:
        lines += ["", "مثال:", "أرسل مسألة فيها الورثة بالتفصيل، وسأطبّق المفهوم عليها بدون تخمين."]

    if c.advanced:
        lines += ["", "تنبيه مهم:", "هذا باب متقدم أو خلافي، فإذا كان السؤال عن حساب مسألة واقعية فلا أحسبها بالتخمين؛ لا يصح حسابها بالتخمين. حدّد المذهب أو الطريقة القضائية المعتمدة والتفاصيل الناقصة."]
    elif c.caution:
        lines += ["", "تنبيه:", c.caution]

    if level == "detailed" and c.related:
        lines += ["", "مفاهيم مرتبطة:", "، ".join(c.related)]

    return "\n".join(lines).strip()


def answer_concept(question: str, dialect="standard", context: Optional[dict]=None) -> Optional[str]:
    key = detect_concept_key(question)
    level = detect_level(question)
    if not key and context and is_followup(question):
        key = context.get("last_concept") or detect_concept_key(context.get("last_question", ""))
    if not key:
        return None
    return render_concept(key, dialect, level)

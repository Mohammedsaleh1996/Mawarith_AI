# Alias index
_ALIAS: List[Tuple[str, str]] = []
for k, c in CONCEPTS.items():
    for a in c.aliases + [c.title]:
        _ALIAS.append((_norm(a), k))
_ALIAS.sort(key=lambda x: len(x[0]), reverse=True)

SIMPLIFY_MARKERS = ["مش فاهم", "مش فاهمه", "مو فاهم", "ما فهمت", "مش واضح", "بسط", "بسطها", "ببساطة", "وضح", "اشرح ابسط", "فهمني"]
EXAMPLE_MARKERS = ["مثال", "بالارقام", "بالأرقام", "طبق", "حالة عملية"]
DETAIL_MARKERS = ["تفصيل", "بالتفصيل", "شرح كامل", "ادلة", "الدليل"]


def detect_level(question: str) -> str:
    n = _norm(question)
    if any(_norm(x) in n for x in EXAMPLE_MARKERS):
        return "example"
    if any(_norm(x) in n for x in SIMPLIFY_MARKERS):
        return "simple"
    if any(_norm(x) in n for x in DETAIL_MARKERS):
        return "detailed"
    return "normal"


def is_followup(question: str) -> bool:
    n = _norm(question)
    return any(_norm(x) in n for x in SIMPLIFY_MARKERS + EXAMPLE_MARKERS + DETAIL_MARKERS) and len(n.split()) <= 8


